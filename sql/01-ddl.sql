BEGIN;
CREATE SCHEMA IF NOT EXISTS liga_facom;
SET search_path TO liga_facom, public;

-- Valores monetários e pontuações usam NUMERIC para evitar erros de arredondamento binário.
CREATE TABLE posicao (
  codigo CHAR(3) PRIMARY KEY,
  nome TEXT NOT NULL UNIQUE,
  fonte_id INTEGER UNIQUE
);
CREATE TABLE situacao (
  codigo TEXT PRIMARY KEY CHECK (codigo IN ('provavel','duvida','suspenso','contundido','nulo')),
  descricao TEXT NOT NULL UNIQUE,
  fonte_id INTEGER UNIQUE
);
CREATE TABLE clube (
  clube_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fonte_id INTEGER NOT NULL UNIQUE,
  nome TEXT NOT NULL UNIQUE,
  abreviacao CHAR(3) NOT NULL UNIQUE,
  escudo_url TEXT
);
CREATE TABLE atleta (
  atleta_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fonte_id INTEGER NOT NULL UNIQUE,
  nome TEXT NOT NULL,
  apelido TEXT NOT NULL,
  posicao CHAR(3) NOT NULL REFERENCES posicao(codigo) ON UPDATE CASCADE ON DELETE RESTRICT,
  situacao TEXT NOT NULL REFERENCES situacao(codigo) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE TABLE rodada (
  rodada_id SMALLINT PRIMARY KEY CHECK (rodada_id BETWEEN 1 AND 38),
  estado TEXT NOT NULL DEFAULT 'fechada' CHECK (estado IN ('aberta','fechada','consolidada')),
  aberta_em TIMESTAMPTZ,
  fechada_em TIMESTAMPTZ,
  consolidada_em TIMESTAMPTZ
);
CREATE UNIQUE INDEX uma_rodada_aberta ON rodada ((estado)) WHERE estado='aberta';
CREATE TABLE clube_rodada (
  atleta_id BIGINT NOT NULL REFERENCES atleta(atleta_id) ON DELETE RESTRICT,
  rodada_id SMALLINT NOT NULL REFERENCES rodada(rodada_id) ON DELETE RESTRICT,
  clube_id BIGINT NOT NULL REFERENCES clube(clube_id) ON DELETE RESTRICT,
  PRIMARY KEY(atleta_id, rodada_id)
);
CREATE TABLE partida (
  partida_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fonte_id INTEGER NOT NULL UNIQUE,
  rodada_id SMALLINT NOT NULL REFERENCES rodada(rodada_id) ON DELETE RESTRICT,
  mandante_id BIGINT NOT NULL REFERENCES clube(clube_id) ON DELETE RESTRICT,
  visitante_id BIGINT NOT NULL REFERENCES clube(clube_id) ON DELETE RESTRICT,
  local TEXT,
  inicio TIMESTAMPTZ,
  gols_mandante SMALLINT CHECK (gols_mandante >= 0),
  gols_visitante SMALLINT CHECK (gols_visitante >= 0),
  valida BOOLEAN NOT NULL DEFAULT TRUE,
  CHECK (mandante_id <> visitante_id),
  UNIQUE(rodada_id,mandante_id,visitante_id)
);
CREATE TABLE scout_tipo (
  sigla TEXT PRIMARY KEY,
  descricao TEXT NOT NULL UNIQUE,
  valor NUMERIC(5,2) NOT NULL,
  posicoes_permitidas CHAR(3)[] -- NULL significa qualquer posição
);
CREATE TABLE atleta_rodada (
  atleta_id BIGINT NOT NULL REFERENCES atleta(atleta_id) ON DELETE RESTRICT,
  rodada_id SMALLINT NOT NULL REFERENCES rodada(rodada_id) ON DELETE RESTRICT,
  entrou_em_campo BOOLEAN NOT NULL DEFAULT FALSE,
  pontuacao NUMERIC(8,2) NOT NULL DEFAULT 0,
  PRIMARY KEY(atleta_id,rodada_id)
);
CREATE TABLE scout_partida (
  atleta_id BIGINT NOT NULL,
  rodada_id SMALLINT NOT NULL,
  partida_id BIGINT NOT NULL REFERENCES partida(partida_id) ON DELETE RESTRICT,
  scout TEXT NOT NULL REFERENCES scout_tipo(sigla) ON UPDATE CASCADE ON DELETE RESTRICT,
  quantidade SMALLINT NOT NULL CHECK (quantidade >= 0),
  PRIMARY KEY(atleta_id,partida_id,scout),
  FOREIGN KEY(atleta_id,rodada_id) REFERENCES atleta_rodada(atleta_id,rodada_id) ON DELETE RESTRICT,
  CHECK (rodada_id > 0)
);
CREATE TABLE esquema (
  nome VARCHAR(5) PRIMARY KEY,
  qtd_gol SMALLINT NOT NULL DEFAULT 1 CHECK(qtd_gol=1),
  qtd_lat SMALLINT NOT NULL CHECK(qtd_lat IN (0,2)),
  qtd_zag SMALLINT NOT NULL CHECK(qtd_zag IN (2,3)),
  qtd_mei SMALLINT NOT NULL CHECK(qtd_mei BETWEEN 3 AND 5),
  qtd_ata SMALLINT NOT NULL CHECK(qtd_ata BETWEEN 1 AND 3),
  qtd_tec SMALLINT NOT NULL DEFAULT 1 CHECK(qtd_tec=1),
  CHECK(qtd_gol+qtd_lat+qtd_zag+qtd_mei+qtd_ata=11)
);
CREATE TABLE tecnico (
  tecnico_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  apelido TEXT NOT NULL,
  cadastrado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE time_fantasy (
  tecnico_id BIGINT PRIMARY KEY REFERENCES tecnico(tecnico_id) ON DELETE CASCADE,
  nome TEXT NOT NULL UNIQUE,
  patrimonio NUMERIC(8,2) NOT NULL DEFAULT 100.00 CHECK(patrimonio >= 0)
);
CREATE TABLE preco_historico (
  atleta_id BIGINT NOT NULL REFERENCES atleta(atleta_id) ON DELETE RESTRICT,
  rodada_id SMALLINT NOT NULL REFERENCES rodada(rodada_id) ON DELETE RESTRICT,
  preco NUMERIC(8,2) NOT NULL CHECK(preco >= 1.00),
  PRIMARY KEY(atleta_id,rodada_id)
);
CREATE TABLE escalacao (
  escalacao_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tecnico_id BIGINT NOT NULL REFERENCES tecnico(tecnico_id) ON DELETE CASCADE,
  rodada_id SMALLINT NOT NULL REFERENCES rodada(rodada_id) ON DELETE RESTRICT,
  esquema TEXT NOT NULL REFERENCES esquema(nome) ON UPDATE CASCADE ON DELETE RESTRICT,
  estado TEXT NOT NULL DEFAULT 'edicao' CHECK(estado IN ('edicao','confirmada')),
  confirmada_em TIMESTAMPTZ,
  UNIQUE(tecnico_id,rodada_id)
);
CREATE TABLE escalacao_item (
  escalacao_id BIGINT NOT NULL REFERENCES escalacao(escalacao_id) ON DELETE CASCADE,
  atleta_id BIGINT NOT NULL REFERENCES atleta(atleta_id) ON DELETE RESTRICT,
  preco_pago NUMERIC(8,2) NOT NULL CHECK(preco_pago >= 1.00),
  capitao BOOLEAN NOT NULL DEFAULT FALSE,
  PRIMARY KEY(escalacao_id,atleta_id)
);
CREATE UNIQUE INDEX um_capitao_por_escalacao ON escalacao_item(escalacao_id) WHERE capitao;
CREATE TABLE liga (
  liga_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dono_id BIGINT NOT NULL REFERENCES tecnico(tecnico_id) ON DELETE RESTRICT,
  nome TEXT NOT NULL,
  descricao TEXT,
  codigo_convite TEXT NOT NULL UNIQUE,
  limite SMALLINT NOT NULL CHECK(limite > 0),
  publica BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE participacao (
  liga_id BIGINT NOT NULL REFERENCES liga(liga_id) ON DELETE CASCADE,
  tecnico_id BIGINT NOT NULL REFERENCES tecnico(tecnico_id) ON DELETE CASCADE,
  entrou_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY(liga_id,tecnico_id)
);

-- O técnico dono também participa obrigatoriamente da liga.
CREATE FUNCTION garantir_dono_participante() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO participacao(liga_id,tecnico_id) VALUES(NEW.liga_id,NEW.dono_id) ON CONFLICT DO NOTHING;
  RETURN NEW;
END $$;
CREATE TRIGGER liga_insere_dono AFTER INSERT ON liga FOR EACH ROW EXECUTE FUNCTION garantir_dono_participante();

-- Inicializa histórico de preço como valor de mercado inserido pela carga.
COMMIT;
